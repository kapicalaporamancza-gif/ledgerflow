log = logging.getLogger(__name__)

_GMAIL_READONLY_SCOPE = "https://www.googleapis.com/auth/gmail.readonly"
_MAX_GOOGLE_ATTEMPTS = 4
_RETRYABLE_HTTP_STATUS_CODES = {429, 500, 502, 503, 504}


class GmailProviderError(RuntimeError):
    """Base error for failures while calling Gmail."""


class GmailAuthError(GmailProviderError):
    """OAuth credentials must be regenerated by the user."""


@dataclass
class IncomingAttachment:
    filename: str
    content: bytes
    mime_type: str = "application/octet-stream"
    attachment_id: str | None = None


@dataclass
class IncomingMessage:
    external_id: str
    sender: str
    subject: str
    body: str
    received_at: str  # ISO
    attachments: list[IncomingAttachment] = field(default_factory=list)


class MailProvider(ABC):
    @abstractmethod
    async def fetch_message(self, message_id: str) -> IncomingMessage: ...

    @abstractmethod
    async def list_recent(self, max_results: int = 20) -> list[IncomingMessage]: ...

    @abstractmethod
    async def download_attachment(self, message_id: str, attachment_id: str) -> bytes: ...


